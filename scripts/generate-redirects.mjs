// Compiles public/_redirects into a JS module the Pages middleware can import.
//
// Cloudflare Pages does not apply `_redirects` to requests handled by Pages
// Functions, and functions/_middleware.js matches every request. So the rules in
// public/_redirects (still the single source of truth — edit that file) are
// re-applied in the middleware from this generated map. Runs as `prebuild`.
import { readFileSync, writeFileSync } from 'node:fs';

const src = readFileSync(new URL('../public/_redirects', import.meta.url), 'utf8');
const map = {};
for (const raw of src.split('\n')) {
  const line = raw.trim();
  if (!line || line.startsWith('#')) continue;
  const [from, to, status = '302'] = line.split(/\s+/);
  if (/[*:]/.test(from)) throw new Error(`Pattern redirects not supported by middleware: ${line}`);
  map[from] = { to, status: Number(status) };
}
const out = `// GENERATED by scripts/generate-redirects.mjs from public/_redirects — do not edit.\nexport default ${JSON.stringify(map, null, 2)};\n`;
writeFileSync(new URL('../functions-lib/redirects.js', import.meta.url), out);
console.log(`[redirects] ${Object.keys(map).length} rules -> functions-lib/redirects.js`);
